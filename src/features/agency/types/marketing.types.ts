/**
 * Marketing Agency (MARKETING_AGENCY activity) — domain types.
 *
 * Records persist in activity-owned collections (mkt_campaigns, mkt_expenses,
 * mkt_deliverables, mkt_briefs, mkt_content_items) whose names come from the
 * shared naming contract (see @/features/activities/types/activity-domain);
 * the Firestore rules gate those prefixes by the tenant's authoritative
 * activity, so a tenant on another activity can neither read nor write them.
 *
 * Clients and contracts are NOT duplicated here: a campaign references the
 * shared CRM records by id (`clientId` -> companies/{c}/contacts, `contractId`
 * -> companies/{c}/contracts), and agency revenue references the shared
 * billing invoices by `campaignId`. Only marketing work products (campaign
 * records, spend, deliverables, briefs, content) live in mkt_ collections.
 *
 * Every status value is a stable machine id — Arabic/English labels live only
 * in the marketing i18n namespace and never double as identifiers.
 */

