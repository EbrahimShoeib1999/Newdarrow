export type CampaignStatus =
  | "draft"
  | "approved"
  | "active"
  | "paused"
  | "completed"
  | "cancelled";

export interface CampaignStatusChange {
  from: CampaignStatus;
  to: CampaignStatus;
  at: string;
  by: string;
  note?: string;
}

/**
 * Approved campaign budgets and revisions. The approved `budgetAmount` is only
 * ever changed through a revision record (pending → approved/rejected), so the
 * audit trail always explains the current number. Amounts are not stored per
 * revision beyond previous/new — never a running total.
 */
export type BudgetRevisionState = "pending" | "approved" | "rejected";

export interface BudgetRevision {
  /** Stable id generated by the service; revisions are embedded, not documents. */
  id: string;
  previousAmount: number;
  newAmount: number;
  reason: string;
  state: BudgetRevisionState;
  proposedBy: string;
  proposedAt: string;
  decidedBy?: string | null;
  decidedAt?: string | null;
}

export interface Campaign {
  id: string;
  /** Transactional human code (CMP-0001), allocated per tenant. */
  code: string;
  name: string;
  objective?: string | null;
  /** Shared CRM contact (customer) this campaign is for — reference, not copy. */
  clientId: string;
  /** Optional shared CRM contract the campaign delivers under. */
  contractId?: string | null;
  channels: CampaignChannel[];
  /** users/{uid} of the responsible agency user. */
  ownerUserId?: string | null;
  startDate?: string | null;
  endDate?: string | null;
  status: CampaignStatus;
  budgetAmount: number;
  currency: string;
  budgetRevisions: BudgetRevision[];
  statusHistory: CampaignStatusChange[];
  notes?: string | null;
  createdAt: string;
  updatedAt: string;
}

export interface CreateCampaignDTO {
  name: string;
  objective?: string | null;
  clientId: string;
  contractId?: string | null;
  channels: CampaignChannel[];
  ownerUserId?: string | null;
  startDate?: string | null;
  endDate?: string | null;
  budgetAmount: number;
  currency: string;
  notes?: string | null;
}
export type UpdateCampaignDTO = Partial<
  Omit<Campaign, "id" | "code" | "status" | "statusHistory" | "budgetRevisions" | "budgetAmount">
>;

/* -------------------------------------------------------------------------- */
/* Campaign spend (actuals) — separate bucket from agency revenue              */
/* -------------------------------------------------------------------------- */

export type ExpenseCategory =
  | "media_buy"
  | "production"
  | "creative"
  | "influencer_fee"
  | "tooling"
  | "event"
  | "other";

export const EXPENSE_CATEGORIES: readonly ExpenseCategory[] = [
  "media_buy",
  "production",
  "creative",
  "influencer_fee",
  "tooling",
  "event",
  "other",
];

/**
 * Actual campaign spend. Agency revenue is NEVER stored here — it is derived
 * from shared billing invoices referencing the campaign (`invoice.campaignId`),
 * so spend and revenue can never be conflated or double-counted.
 */
export interface CampaignExpense {
  id: string;
  campaignId: string;
  title: string;
  category: ExpenseCategory;
  amount: number;
  /** ISO date (yyyy-mm-dd) the spend occurred. */
  spentAt: string;
  vendorName?: string | null;
  currency: string;
  note?: string | null;
  createdAt: string;
  updatedAt: string;
}

export type CreateCampaignExpenseDTO = Omit<
  CampaignExpense,
  "id" | "createdAt" | "updatedAt"
>;
export type UpdateCampaignExpenseDTO = Partial<
  Omit<CampaignExpense, "id" | "createdAt" | "updatedAt">
>;

